const high = {};
const review = {};
const missingTranslations = [];

for (const r of raw) {
  if (!T[r.slug]) {
    missingTranslations.push(r.slug);
    continue;
  }
  const t = T[r.slug];
  const entry = {
    slug: r.slug,
    nameEn: r.nameEn,
    nameTh: t.nameTh,
    type: r.type,
    damageClass: r.damageClass,
    power: r.power,
    accuracy: r.accuracy,
    pp: r.pp,
    priority: r.priority,
    description: t.description,
    category: t.category,
  };
  if (t.effect) entry.effect = t.effect;

  if (REVIEW_NOTES[r.slug]) {
    entry.reviewReason = REVIEW_NOTES[r.slug];
    review[r.slug] = entry;
  } else {
    high[r.slug] = entry;
  }
}

if (missingTranslations.length > 0) {
  console.error('ERROR: missing translations for:');
  missingTranslations.forEach((s) => console.error(' -', s));
  process.exit(1);
}

