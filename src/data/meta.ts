/**
 * Pokémon Champions — Regulation M-A meta list
 *
 * Source: Showdowntier (usage/winrate aggregated from 273+ tournaments)
 *         + Beebom/PokémonZone tier lists, mid-May 2026 snapshot.
 *
 * Reg M-A rules (current as of 2026-05-15):
 *  - Banned: All Paradox Pokémon, all four Treasures of Ruin,
 *            Koraidon, Miraidon, restricted legendaries.
 *  - Items: Unique (no two Pokémon may hold the same item).
 *           Life Orb / Choice Band / Choice Specs / Choice Scarf
 *           are NOT available in Pokémon Champions at launch.
 *  - Gimmicks: Mega Evolution + Terastallization both available
 *              (one-gimmick-per-battle limit per player).
 *  - Formats: Singles and Doubles. Tier data below reflects Doubles
 *             (the primary ranked format).
 */

import type { TypeId } from './types';

export type Tier = 'S' | 'A' | 'B' | 'C' | 'Restricted';

/**
 * Pokémon Champions uses a NEW stat system (not EV/IV/Nature):
 *   - Stat Points (SP): 66 total per Pokémon, max 32 per stat (replaces EVs)
 *   - IVs: locked at 31 for ALL Pokémon — no breeding/hyper training needed
 *   - Stat Alignment: same as Nature (+10%/-10%), but renamed and freely changeable via VP
 *   - Level: auto-scaled to 50 in ranked battles
 *
 * Conversion from mainline:
 *   - 252 EV  →  32 SP (capped)
 *   - 4 EV    →  0–2 SP
 *   - Total 510 EV → 66 SP budget
 */
export interface CompetitiveSet {
  name: string;
  item: string;
  ability: string;
  alignment: string;       // Stat Alignment (was: Nature)
  sp: string;              // Stat Points spread, e.g. "32 HP / 32 Atk / 2 Spe"
  teraType?: string;
  moves: string[];
}

export interface MetaPokemon {
  // Identification
  id: number;        // PokéAPI ID (use for sprite)
  slug: string;      // URL slug (used in /pokemon/[slug])
  nameEn: string;
  nameTh?: string;

  // Battle data
  types: TypeId[];
  baseStats: {
    hp: number;
    atk: number;
    def: number;
    spa: number;
    spd: number;
    spe: number;
  };
  abilities: string[];
  hiddenAbility?: string;

  // Champions-specific
  tier: Tier;
  usagePercent?: number;
  winRate?: number;
  role: string;
  roleTh: string;
  description: string;
  strengths: string[];
  weaknesses: string[];
  commonItems: string[];
  commonMoves: string[];
  sets?: CompetitiveSet[];
  counters?: string[];
  teammates?: string[];

  // Mega Evolution info
  hasMega?: boolean;
  megaForm?: string;
}

export function spriteUrl(id: number, shiny = false): string {
  const dir = shiny
    ? 'https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/official-artwork/shiny'
    : 'https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/official-artwork';
  return `${dir}/${id}.png`;
}

